#!/usr/bin/env node

/**
 * Copies docs/template-guide.md into the app (src/content/template-guide.ts), so the Guide tab
 * and the repo show the same text. Runs before every web build; run it by hand (npm run guide)
 * after editing the guide to see the change in `expo start`.
 */
const fs = require('fs');
const path = require('path');

const root = process.cwd(); // npm runs scripts from the project folder
const markdown = fs.readFileSync(path.join(root, 'docs', 'template-guide.md'), 'utf8').replace(/\r\n/g, '\n');
const out = path.join(root, 'src', 'content', 'template-guide.ts');

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// Generated by scripts/build-guide.js from docs/template-guide.md. Edit that file, not this one.\n` +
    `export const TEMPLATE_GUIDE = ${JSON.stringify(markdown)};\n`,
);
console.log(`Guide copied to ${path.relative(root, out)}`);
